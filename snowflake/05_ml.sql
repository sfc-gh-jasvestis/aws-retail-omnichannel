-- Fulfilment-disruption risk scoring and late-order forecast over the synthetic snapshot.
-- Predicts P(fulfilment disruption at the node in the next 7 days) per node and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.DISRUPTION_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, z.CATEGORY, z.STORE_TIER, z.STORE_AGE_YEARS,
       r.AVG_PICK_PASSES, r.AVG_FULFIL_HOURS,
       AVG(r.AVG_FULFIL_HOURS) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS FULFIL_HOURS_7D,
       SUM(r.DISRUPTION_HOURS) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS DISRUPTION_HOURS_30D,
       IFF(SUM(r.DISRUPTION_HOURS) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'DISRUPTION', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.STORE_DAILY r JOIN RAW.STORES z ON z.ID = r.ENTITY_ID
-- Mega-sale order surges are not node-driven, so those days are excluded from training.
WHERE r.DISRUPTION_CAUSE <> 'Mega-sale order surge';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.DISRUPTION_TRAIN AS
SELECT CATEGORY, STORE_TIER, STORE_AGE_YEARS, AVG_PICK_PASSES, AVG_FULFIL_HOURS, FULFIL_HOURS_7D, DISRUPTION_HOURS_30D, LABEL
FROM ML.DISRUPTION_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.DISRUPTION_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, STORE_TIER, STORE_AGE_YEARS, AVG_PICK_PASSES, AVG_FULFIL_HOURS, FULFIL_HOURS_7D, DISRUPTION_HOURS_30D, LABEL
FROM ML.DISRUPTION_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.DISRUPTION_RISK_MODEL(
  INPUT_DATA => TABLE(ML.DISRUPTION_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.DISRUPTION_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.DISRUPTION_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'STORE_TIER', STORE_TIER, 'STORE_AGE_YEARS', STORE_AGE_YEARS,
           'AVG_PICK_PASSES', AVG_PICK_PASSES, 'AVG_FULFIL_HOURS', AVG_FULFIL_HOURS,
           'FULFIL_HOURS_7D', FULFIL_HOURS_7D, 'DISRUPTION_HOURS_30D', DISRUPTION_HOURS_30D)):probability:DISRUPTION::FLOAT AS P
  FROM ML.DISRUPTION_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'DISRUPTION', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'DISRUPTION', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'DISRUPTION', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'DISRUPTION', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per node (label unknown, so excluded from features).
CREATE TABLE ML.DISRUPTION_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.DISRUPTION_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.DISRUPTION_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'STORE_TIER', STORE_TIER, 'STORE_AGE_YEARS', STORE_AGE_YEARS,
           'AVG_PICK_PASSES', AVG_PICK_PASSES, 'AVG_FULFIL_HOURS', AVG_FULFIL_HOURS,
           'FULFIL_HOURS_7D', FULFIL_HOURS_7D, 'DISRUPTION_HOURS_30D', DISRUPTION_HOURS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:DISRUPTION::FLOAT, 4) AS DISRUPTION_PROB_7D,
       CASE WHEN P:probability:DISRUPTION::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:DISRUPTION::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide late-order forecast (14 days) from the daily series, for picker capacity planning.
CREATE VIEW ML.DAILY_LATE AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(LATE_COUNT)::FLOAT AS LATE_COUNT
FROM RAW.STORE_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.LATE_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_LATE),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'LATE_COUNT'
);

CREATE TABLE ML.LATE_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS LATE_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.LATE_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));

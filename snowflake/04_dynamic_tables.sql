-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT store.ID AS ENTITY_ID, store.NAME AS ENTITY_NAME,
       store.REGION, store.CATEGORY, store.STORE_TIER, store.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.ORDER_COUNT) AS ORDER_COUNT,
       SUM(observation.FULFILLED_COUNT) AS FULFILLED_COUNT,
       SUM(observation.LATE_COUNT) AS LATE_COUNT,
       SUM(observation.CANCELLED_COUNT) AS CANCELLED_COUNT,
       SUM(observation.NET_SALES_SGD) AS NET_SALES_SGD,
       SUM(observation.DISRUPTION_HOURS) AS DISRUPTION_HOURS,
       COUNT_IF(observation.DISRUPTION_HOURS > 0) AS DISRUPTION_DAYS,
       SUM(observation.SYNC_DUE) AS SYNC_DUE,
       SUM(observation.SYNC_DONE) AS SYNC_DONE,
       100.0 * SUM(observation.FULFILLED_COUNT) / NULLIF(SUM(observation.ORDER_COUNT), 0) AS ON_TIME_PCT,
       100.0 * SUM(observation.CANCELLED_COUNT) / NULLIF(SUM(observation.ORDER_COUNT), 0) AS CANCEL_PCT,
       100.0 * SUM(observation.SYNC_DONE) / NULLIF(SUM(observation.SYNC_DUE), 0) AS SYNC_ON_TIME_PCT,
       AVG(observation.AVG_PICK_PASSES) AS AVG_PICK_PASSES,
       AVG(observation.AVG_FULFIL_HOURS) AS AVG_FULFIL_HOURS,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.STORE_DAILY observation
JOIN RAW.STORES store ON store.ID = observation.ENTITY_ID
GROUP BY store.ID, store.NAME, store.REGION, store.CATEGORY, store.STORE_TIER, store.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(ORDER_COUNT) AS ORDER_COUNT, SUM(FULFILLED_COUNT) AS FULFILLED_COUNT,
       SUM(LATE_COUNT) AS LATE_COUNT, SUM(DISRUPTION_HOURS) AS DISRUPTION_HOURS,
       SUM(NET_SALES_SGD) AS NET_SALES_SGD,
       100.0 * SUM(FULFILLED_COUNT) / NULLIF(SUM(ORDER_COUNT), 0) AS ON_TIME_PCT
FROM RAW.STORE_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.CAUSE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT DISRUPTION_CAUSE, COUNT(*) AS DISRUPTION_DAYS,
       SUM(DISRUPTION_HOURS) AS DISRUPTION_HOURS,
       SUM(LATE_COUNT) AS LATE_COUNT,
       SUM(ORDER_COUNT) AS ORDER_COUNT,
       100.0 * SUM(LATE_COUNT) / NULLIF(SUM(ORDER_COUNT), 0) AS LATE_PCT
FROM RAW.STORE_DAILY
WHERE DISRUPTION_HOURS > 0
GROUP BY DISRUPTION_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ORDER_COUNT) AS ORDERS, SUM(FULFILLED_COUNT) AS FULFILLED,
         SUM(LATE_COUNT) AS LATE, SUM(CANCELLED_COUNT) AS CANCELLED,
         SUM(DISRUPTION_HOURS) AS DISRUPTION_HOURS, COUNT_IF(DISRUPTION_HOURS > 0) AS DISRUPTION_DAYS,
         SUM(NET_SALES_SGD) AS NET_SALES_SGD, SUM(SYNC_DUE) AS SYNC_DUE, SUM(SYNC_DONE) AS SYNC_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.STORE_DAILY
), book AS (SELECT COUNT(*) AS STORE_COUNT FROM RAW.STORES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.STAFF_TRAINING
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'On-Time Fulfilment Rate' AS TITLE,
         100.0 * FULFILLED / NULLIF(ORDERS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Late Orders', LATE, '' FROM observations
  UNION ALL SELECT 3, 'Fulfilment Disruption Hours', DISRUPTION_HOURS, '' FROM observations
  UNION ALL SELECT 4, 'Order Cancellation Rate', 100.0 * CANCELLED / NULLIF(ORDERS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Disruption Node-Days', DISRUPTION_DAYS, '' FROM observations
  UNION ALL SELECT 6, 'Net Sales (SGD M)', NET_SALES_SGD / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Orders Fulfilled On Time', FULFILLED, '' FROM observations
  UNION ALL SELECT 8, 'Cycle Count On-Time Rate', 100.0 * SYNC_DONE / NULLIF(SYNC_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Fulfilment Nodes Monitored', STORE_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Staff Training Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Staff Trainings Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.CAUSE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
